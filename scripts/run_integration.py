"""Run real integration tests in an isolated test database and retain JUnit output."""
from datetime import datetime, timezone
from pathlib import Path
import base64
import binascii
import os
import subprocess
import uuid
import xml.etree.ElementTree as ET

try:
    from scripts.preflight import docker_binary
    from scripts.retain_release import check_build_source
except ModuleNotFoundError:
    from preflight import docker_binary
    from retain_release import check_build_source

REPORT_BEGIN = "__DATA_HORIZON_JUNIT_BASE64_BEGIN__"
REPORT_END = "__DATA_HORIZON_JUNIT_BASE64_END__"


def extract_junit(output: str) -> bytes:
    lines = output.splitlines()
    if lines.count(REPORT_BEGIN) != 1 or lines.count(REPORT_END) != 1:
        raise ValueError("Integration JUnit evidence is missing or has ambiguous transport markers")
    start, end = lines.index(REPORT_BEGIN), lines.index(REPORT_END)
    if end <= start:
        raise ValueError("Integration JUnit transport markers are out of order")
    payload = "".join(lines[start + 1:end])
    if len(payload) > 12 * 1024 * 1024:
        raise ValueError("Integration JUnit evidence exceeds the size limit")
    try:
        xml = base64.b64decode(payload, validate=True)
        document = ET.fromstring(xml)
    except (ValueError, binascii.Error, ET.ParseError) as exc:
        raise ValueError("Integration JUnit evidence is malformed") from exc
    if document.tag not in {"testsuite", "testsuites"} or not list(document.iter("testcase")):
        raise ValueError("Integration JUnit evidence contains no executed test cases")
    return xml


def test_wrapper() -> str:
    # Emit before exit: /tmp is a tmpfs and cannot be copied after container stop.
    return (
        "import base64,pathlib,pytest; "
        "result=pytest.main(['tests/test_integration.py','-v','-o','cache_dir=/tmp/pytest-cache',"
        "'--junitxml=/tmp/integration.xml']); "
        "path=pathlib.Path('/tmp/integration.xml'); "
        f"print({REPORT_BEGIN!r},flush=True); "
        "print(base64.b64encode(path.read_bytes()).decode('ascii'),flush=True); "
        f"print({REPORT_END!r},flush=True); "
        "raise SystemExit(result)"
    )


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    output = root / "reports/raw"
    output.mkdir(parents=True, exist_ok=True)
    executable = docker_binary()
    if not executable:
        raise SystemExit("Docker CLI is unavailable")
    environment = dict(os.environ)
    if environment.get("DATA_MODE", "synthetic") != "synthetic":
        raise SystemExit("Use DATA_MODE=synthetic for integration tests")
    environment["DATA_MODE"] = "synthetic"
    environment["PATH"] = "/Applications/Docker.app/Contents/Resources/bin:" + environment.get("PATH", "")
    command = [executable, "compose", "--profile", "test"]
    revision = environment.get("VCS_REF") or subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=root, capture_output=True, text=True, check=True, timeout=20,
    ).stdout.strip()
    check_build_source(root, revision, scope="backend")
    subprocess.run(command + ["build", "--build-arg", "VCS_REF=" + revision, "integration"],
                   cwd=root, env=environment, check=True)
    name = "horizon-integration-" + uuid.uuid4().hex[:12]
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    destination = output / f"integration-{timestamp}.xml"
    try:
        result = subprocess.run(command + ["run", "--name", name, "-T", "integration", "python", "-c", test_wrapper()],
                                cwd=root, env=environment, timeout=600, text=True,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        captured = result.stdout
        ordinary_output = captured.split(REPORT_BEGIN, 1)[0]
        print(ordinary_output, end="" if ordinary_output.endswith("\n") else "\n")
        xml = extract_junit(captured)
        destination.write_bytes(xml)
        print(f"Integration evidence: {destination}")
        return result.returncode
    finally:
        # This name was generated by this invocation; no application volume is removed.
        subprocess.run([executable, "rm", "-f", name], cwd=root, env=environment,
                       capture_output=True, timeout=30)


if __name__ == "__main__":
    raise SystemExit(main())
